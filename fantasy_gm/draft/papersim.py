"""Task 3.8 — reproduce the published H₀ simulation, as a correctness check on our engine.

Every number this project has reported for H₀ comes from :mod:`fantasy_gm.draft.replay`, which
measures a *different quantity* from the one the paper reports. Before concluding that the
published method does not work on real data, we have to know that our implementation of it
reproduces the published result in the published setting. That is what this module is for.

**The published experiment** (Rosenof, *Dynamic quantification of player value for fantasy
basketball*, arXiv:2409.09884):

* one H₀ drafter against **eleven G-score drafters**, twelve teams, thirteen rounds, snake;
* each simulated season is **twenty weeks**, generated by resampling each player's own real
  weekly performances (injured weeks excluded);
* the drafters know the true distributions exactly — there is no projection error, so the only
  thing under test is the drafting;
* the reported statistic is **the share of seasons the H₀ team finishes first**, against a
  chance baseline of 1/12 = 8.3%. Published: **21.8% (Each Category), 37.7% (Most Categories)**,
  averaged over the twelve draft seats.

**What our replay harness measures instead**: category win rate for H₀ seated alongside a
G-score board, a z-score board and nine ADP bots, on one realized season, graded all-play-all.
Neither the field, the metric, the opponent model, nor the number of seasons matches. A deficit
there is not evidence against the published result until this file says whether we can produce
that result at all.

**The draft is run once per seat, not once per simulated season.** Both drafters see only the
true distributions, which do not vary between simulations, and both are deterministic — so the
rosters are identical in every one of the N seasons. Resampling the draft would burn the entire
compute budget re-deriving the same thirteen picks. The paper's thousand seasons per seat vary
the *season*, and so do ours.

**Stated deviations from the published setup**, each of which applies equally to both arms:

1. *Three seasons of weekly panels, not twenty.* We hold 2023-24 through 2025-26. Each season is
   run as its own experiment and reported separately, which is how every other table in this
   project reads.
2. *No positional eligibility.* The paper constrains rosters to a thirteen-slot position
   structure. Our draft has no positional constraint and — see ``assignment.py``, which nothing
   calls — our H₀ objective has no positional assignment term either. This is a genuine gap in
   the implementation, recorded rather than papered over.
3. *Round-robin standings.* The paper does not state its schedule. A team wins its season by
   topping the standings of a rotating round-robin: total category wins under Each Category,
   total matchup wins under Most Categories. Ties split the title.
"""

